"""Step 5 · PROVE — Claude vs our fine-tuned model, side by side.

Reads two eval_runs rows and writes docs/FINETUNE_RESULTS.md. The two runs
come from the SAME harness over the SAME 22 golden questions with the SAME
retrieval — only the answering model differs, which is what makes the numbers
mean anything.

    # 1. baseline
    LLM_PROVIDER=anthropic  python eval/run_eval.py --notes "baseline: claude"
    # 2. ours (Ollama must be running)
    LLM_PROVIDER=local      python eval/run_eval.py --notes "brainstack-3b"
    # 3. the table
    python training/compare_eval.py

By default it takes the two most recent runs and puts the OLDER one in the
baseline column. Override with --baseline / --candidate (row id prefixes).

One metric here is not in the eval_runs table: refusal-on-traps. It is
computed from per_question, because "did it refuse when it should have" is the
single number a small model is most likely to fail, and averaging it into
retrieval_hit hides it.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from sqlalchemy import create_engine, select  # noqa: E402
from sqlalchemy.orm import Session  # noqa: E402

from app.config import get_settings  # noqa: E402
from app.models import EvalRun  # noqa: E402

OUT = ROOT / "docs" / "FINETUNE_RESULTS.md"

# Everything after this line in the output file is hand-written and is
# preserved across regenerations.
MANUAL_MARKER = "<!-- MANUAL ANALYSIS BELOW — preserved by compare_eval.py -->"


def trap_refusal_rate(rows: list[dict]) -> tuple[int, int]:
    traps = [r for r in rows if r.get("expect_refusal")]
    return sum(1 for r in traps if r.get("refused")), len(traps)


def avg_latency_s(rows: list[dict]) -> float | None:
    vals = [r["latency_ms"] for r in rows if r.get("latency_ms")]
    return statistics.mean(vals) / 1000 if vals else None


def arrow(base: float, cand: float, higher_is_better: bool = True) -> str:
    d = cand - base
    if abs(d) < 0.0005:
        return "="
    good = (d > 0) if higher_is_better else (d < 0)
    return f"{'+' if d > 0 else ''}{d:.3f} {'✅' if good else '⚠️'}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--baseline", help="eval run id prefix (default: older of the last two)")
    ap.add_argument("--candidate", help="eval run id prefix (default: newest)")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    engine = create_engine(get_settings().sqlalchemy_url)
    with Session(engine) as s:
        if args.baseline or args.candidate:
            runs = list(s.scalars(select(EvalRun).order_by(EvalRun.created_at.desc())))

            def pick(prefix):
                m = [r for r in runs if str(r.id).startswith(prefix)]
                if not m:
                    raise SystemExit(f"no eval run starts with {prefix!r}")
                return m[0]

            candidate = pick(args.candidate) if args.candidate else runs[0]
            baseline = pick(args.baseline) if args.baseline else runs[1]
        else:
            last_two = list(
                s.scalars(select(EvalRun).order_by(EvalRun.created_at.desc()).limit(2))
            )
            if len(last_two) < 2:
                raise SystemExit(
                    "need two eval runs — run eval/run_eval.py once per provider first"
                )
            candidate, baseline = last_two[0], last_two[1]

        pairs = []
        for run in (baseline, candidate):
            rows = json.loads(run.per_question or "[]")
            pairs.append((run, rows))

    (base_run, base_rows), (cand_run, cand_rows) = pairs
    b_ref, b_traps = trap_refusal_rate(base_rows)
    c_ref, c_traps = trap_refusal_rate(cand_rows)
    b_lat, c_lat = avg_latency_s(base_rows), avg_latency_s(cand_rows)

    lines: list[str] = []
    w = lines.append

    w("# 📊 Fine-tuning results — Claude vs our own model\n")
    w("> Generated by `training/compare_eval.py`. Both runs use the **same**")
    w("> 22 golden questions, the **same** retrieval pipeline and the **same**")
    w("> judges — only the model that writes the answer differs.\n")
    w(f"- **Baseline:** `{base_run.model}` — {base_run.notes or 'no notes'}"
      f" · {base_run.created_at:%Y-%m-%d %H:%M}")
    w(f"- **Ours:** `{cand_run.model}` — {cand_run.notes or 'no notes'}"
      f" · {cand_run.created_at:%Y-%m-%d %H:%M}")
    w(f"- **Questions:** {base_run.dataset_size}\n")

    w("## The table\n")
    w(f"| Metric | {base_run.model} | {cand_run.model} | Δ |")
    w("|---|---:|---:|---|")
    for label, attr in (
        ("faithfulness — did it invent anything?", "faithfulness"),
        ("relevance — did it answer the question?", "relevance"),
        ("retrieval_hit — did the right passages come back?", "retrieval_hit"),
        ("citation_validity — are the [n] real?", "citation_validity"),
    ):
        b, c = getattr(base_run, attr), getattr(cand_run, attr)
        w(f"| {label} | {b:.3f} | {c:.3f} | {arrow(b, c)} |")

    if b_traps:
        w(f"| refusal on traps — did it say \"I don't know\"? | "
          f"{b_ref}/{b_traps} | {c_ref}/{c_traps} | "
          f"{arrow(b_ref / b_traps, c_ref / c_traps)} |")
    if b_lat and c_lat:
        w(f"| avg latency per question | {b_lat:.1f}s | {c_lat:.1f}s | "
          f"{arrow(b_lat, c_lat, higher_is_better=False)} |")
    # Only claim zero cost when the candidate really is the local model —
    # otherwise this row is a lie in the deliverable document.
    if cand_run.model == get_settings().LLM_MODEL_LOCAL:
        w("| API cost | metered per token | **$0.00** — runs on hardware we own | — |")
    w("")

    w("## Where ours disagreed with the baseline\n")
    by_id = {r["id"]: r for r in base_rows if "id" in r}
    worse = []
    for r in cand_rows:
        b = by_id.get(r.get("id"))
        if not b:
            continue
        if (
            r["faithfulness"] < b["faithfulness"]
            or r["relevance"] < b["relevance"]
            or (b["citation_valid"] and not r["citation_valid"])
            or (b.get("refused") and not r.get("refused") and r.get("expect_refusal"))
        ):
            worse.append((r, b))

    if not worse:
        w("None — our model matched or beat the baseline on every question.\n")
    else:
        w(f"{len(worse)} of {len(cand_rows)} questions. This is the list to mine "
          "for the next round of training data.\n")
        for r, b in worse:
            w(f"**q{r['id']} — {r['question']}**\n")
            w(f"- baseline: faith {b['faithfulness']:.1f} · rel {b['relevance']:.1f} "
              f"· cite {'ok' if b['citation_valid'] else 'BAD'}")
            w(f"- ours: faith {r['faithfulness']:.1f} · rel {r['relevance']:.1f} "
              f"· cite {'ok' if r['citation_valid'] else 'BAD'}")
            if r.get("faithfulness_why"):
                w(f"- judge said: _{r['faithfulness_why']}_")
            w(f"- our answer: `{(r.get('answer') or '')[:300]}`\n")

    w("## Reading this honestly\n")
    w("A 3B model quantized to 4 bits and served on a CPU is not supposed to")
    w("beat Claude, and did not need to. What it had to show is that the")
    w("*trained behaviour* transferred: cite real passages, refuse when the")
    w("answer isn't there. Those two rows are the result. Faithfulness and")
    w("latency are the price, and both were known before we started —")
    w("production stays on Claude for exactly that reason.\n")

    w("## What I'd do next\n")
    w("- [ ] more training data on whatever question types failed above")
    w("- [ ] raise the refusal share if traps leaked through")
    w("- [ ] try `r=32` — more adapter capacity, still minutes to train")
    w("- [ ] try a 7B base if a GPU is ever available; the pipeline is unchanged\n")

    # Anything below the marker is hand-written analysis — carry it across a
    # regeneration instead of silently deleting it. The generated table is
    # cheap to rebuild; the investigation that explains it is not.
    out = Path(args.out)
    manual = ""
    if out.exists():
        prev = out.read_text(encoding="utf-8")
        if MANUAL_MARKER in prev:
            manual = "\n" + prev.split(MANUAL_MARKER, 1)[1].lstrip("\n")
    out.write_text("\n".join(lines) + (MANUAL_MARKER + manual if manual else ""), encoding="utf-8")
    print("\n".join(lines[: 14 + 6]))
    print(f"\n  wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
